let lang = (() => {
  try { return localStorage.getItem(KEY) || 'zh'; } catch { return 'zh'; }
})();

const listeners = new Set();

export function getLang() { return lang; }

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'zh';
  try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang === 'zh' ? 'zh-Hant' : 'en';
  for (const fn of listeners) fn(lang);
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function isZh() { return lang === 'zh'; }

// Look up a key with optional {placeholder} interpolation.
export function t(key, vars) {
  const table = DICT[lang] || DICT.zh;
  let s = table[key];
  if (s == null) s = DICT.zh[key];
  if (s == null) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

// Pick the right field from a bilingual object ({name, name_zh} etc.).
export function bi(obj, base) {
  if (!obj) return '';
  if (lang === 'zh') return obj[`${base}_zh`] || obj[base] || '';
  return obj[base] || obj[`${base}_zh`] || '';
}

// The active display currency for the current language.
export function currency() {
  return lang === 'zh'
    ? { code: 'HKD', symbol: 'HK$', rate: 7.8 }
    : { code: 'USD', symbol: 'US$', rate: 1 };
}

// Format a base (USD) amount in the active currency.
export function money(usd, opts = {}) {
  const c = currency();
  const v = usd * c.rate;
  const decimals = opts.decimals != null ? opts.decimals : (v >= 100 ? 0 : 2);
  return `${c.symbol}${v.toLocaleString(lang === 'zh' ? 'zh-HK' : 'en-US', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })}`;
}

export function dateLabel(iso, opts = {}) {
  const d = new Date(iso);
  return d.toLocaleDateString(lang === 'zh' ? 'zh-HK' : 'en-US', opts.year ? { year: 'numeric', month: 'short', day: 'numeric' } : { month: 'short', day: 'numeric' });
}
